"""Compare offline builders against the untouched Git revision in temporary copies."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
BASELINE = "57b6dc8"

def hashes(folder):
    return {str(p.relative_to(folder)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in folder.rglob("*") if p.is_file()}

with tempfile.TemporaryDirectory(prefix="infovis-python-") as temp:
    temp = Path(temp)
    archive = temp / "baseline.tar"
    with archive.open("wb") as output:
        subprocess.run(["git", "archive", BASELINE], cwd=ROOT, stdout=output, check=True)
    before, after = temp / "before", temp / "after"
    before.mkdir()
    with tarfile.open(archive) as source:
        source.extractall(before, **({"filter":"data"} if sys.version_info >= (3, 12) else {}))
    shutil.copytree(before, after)
    shutil.rmtree(after / "python_scripts")
    shutil.copytree(ROOT / "python_scripts", after / "python_scripts", ignore=shutil.ignore_patterns("__pycache__"))
    # Raw download archives are intentionally not committed. Exercise the grid
    # builder with the same compact input on both sides, including thresholds.
    for repo in [before, after]:
        staging = repo / "gbif/staging"
        staging.mkdir(parents=True, exist_ok=True)
        for resolution in [0.2, 0.05]:
            cells = [[-350, -170, 7, [[100, 70, 20, 2] for _ in range(12)], [8]*12],
                     [-351, -170, 7, [[10, 5, 2, 1] for _ in range(12)], [2]*12],
                     [-352, -171, 16, [[40, 50, 80, 0] for _ in range(12)], [4]*12]]
            (staging / f"grid-{resolution}.json").write_text(json.dumps({"res":resolution,"years":[2017,2024],"cells":cells}))
    commands = ["build_web_data.py", "build_overview_data.py", "build_grid_data.py", "build_loop_data.py", "build_game_data.py"]
    for command in commands:
        for repo in [before, after]:
            result = subprocess.run([sys.executable, str(repo / "python_scripts" / command)], cwd=repo,
                                    env={**os.environ, "PYTHONDONTWRITEBYTECODE":"1"}, capture_output=True, text=True)
            if result.returncode:
                raise RuntimeError(f"{repo.name}/{command}\n{result.stdout}\n{result.stderr}")
        assert hashes(before / "web/data") == hashes(after / "web/data"), command
        print(f"PASS {command}: identical generated bytes")
    # New paths can also be run directly, without relying on the old entrypoints.
    for command in ["atlas/build_web_data.py", "overview/build_overview_data.py", "overview/build_grid_data.py",
                    "overview/build_loop_data.py", "aviary/build_game_data.py"]:
        subprocess.run([sys.executable, str(after / "python_scripts" / command)], cwd=after, check=True, stdout=subprocess.DEVNULL)
    assert hashes(before / "web/data") == hashes(after / "web/data")
    print("PASS direct entrypoints: identical generated bytes")
